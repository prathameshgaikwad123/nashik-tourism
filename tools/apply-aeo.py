#!/usr/bin/env python3
"""
Give every hand-written guide the answer-engine upgrades, from front-matter in
data/pages.json — idempotent, marker-based, never touches the author's prose:

  <!-- BEGIN:NT-QA -->      the 40-60 word quick answer, first thing in the article
  <!-- BEGIN:NT-OFFICIAL --> optional 'Official status as of <date>' box (front-matter officialStatus)
  <!-- BEGIN:NT-BYLINE -->  "By <author> · Last updated · Last verified" under the hero
  <!-- BEGIN:NT-LD -->      JSON-LD graph in <head>: Article (author and publisher = the site's
                            Organization, datePublished, dateModified, mainEntityOfPage),
                            BreadcrumbList (parsed from the visible breadcrumb), FAQPage
                            (parsed from the visible FAQ) and the Person / Organization nodes
  <!-- BEGIN:NT-HEAD -->    optional <meta name="msvalidate.01"> and cookieless analytics (env)

Any earlier Article / FAQPage / BreadcrumbList / WebPage JSON-LD block in the head is
replaced, so the markup always matches what is on the page.

    python3 tools/apply-aeo.py [--check]
"""
import html as htmllib
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nt import aeo, store  # noqa: E402
from nt.render import esc, fmt_date  # noqa: E402
from nt.paths import ROOT, SITE  # noqa: E402

QA_RE = re.compile(r"[ \t]*<!-- BEGIN:NT-QA -->.*?<!-- END:NT-QA -->\n?", re.S)
LK_RE = re.compile(r"[ \t]*<!-- BEGIN:NT-LINKS -->.*?<!-- END:NT-LINKS -->\n?", re.S)
OF_RE = re.compile(r"[ \t]*<!-- BEGIN:NT-OFFICIAL -->.*?<!-- END:NT-OFFICIAL -->\n?", re.S)
BY_RE = re.compile(r"[ \t]*<!-- BEGIN:NT-BYLINE -->.*?<!-- END:NT-BYLINE -->\n?", re.S)
LD_RE = re.compile(r"[ \t]*<!-- BEGIN:NT-LD[^>]*-->.*?<!-- END:NT-LD -->\n?", re.S)
HD_RE = re.compile(r"[ \t]*<!-- BEGIN:NT-HEAD[^>]*-->.*?<!-- END:NT-HEAD -->\n?", re.S)
SCRIPT_RE = re.compile(r'[ \t]*<script type="application/ld\+json">(.*?)</script>\n?', re.S)
LINK_TOPICS = {"kumbh", "transport", "destination", "accommodation"}
STRIP_TYPES = {"Article", "BlogPosting", "FAQPage", "BreadcrumbList", "WebPage"}


def head_block():
    extra = "\n  ".join(x for x in (aeo.bing_meta(), aeo.analytics_head()) if x)
    return "<!-- BEGIN:NT-HEAD (generated by tools/apply-aeo.py) -->\n  %s\n  <!-- END:NT-HEAD -->" % extra if extra else ""


def strip_old_ld(html):
    def keep(m):
        try:
            data = json.loads(m.group(1))
        except ValueError:
            return m.group(0)
        types = set()
        for node in (data.get("@graph") if isinstance(data, dict) and "@graph" in data else [data]):
            t = node.get("@type") if isinstance(node, dict) else None
            types.update(t if isinstance(t, list) else [t])
        return "" if types & STRIP_TYPES else m.group(0)
    return SCRIPT_RE.sub(keep, html)


def visible_breadcrumb(html):
    m = re.search(r'<div class="breadcrumb">(.*?)</div>|<nav class="breadcrumb"[^>]*>(.*?)</nav>', html, re.S)
    if not m:
        return None
    inner = m.group(1) or m.group(2)
    crumbs = []
    for part in re.split(r'<span[^>]*>[^<]*</span>', inner):
        a = re.search(r'<a href="([^"]*)"[^>]*>(.*?)</a>', part, re.S)
        if a:
            crumbs.append((aeo.plain(a.group(2)), a.group(1)))
        elif aeo.plain(part):
            crumbs.append((aeo.plain(part), None))
    return crumbs or None


def meta_content(html, key, attr="name"):
    m = re.search(r'<meta %s="%s" content="([^"]*)"' % (attr, re.escape(key)), html)
    return htmllib.unescape(m.group(1)) if m else None


def ld_block(html, path, meta):
    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", html, re.S)
    headline = aeo.plain(h1.group(1)) if h1 else aeo.plain(re.search(r"<title>(.*?)</title>", html, re.S).group(1))
    desc = meta_content(html, "description") or ""
    image = meta_content(html, "og:image", "property")
    modified = aeo.modified_for(path, meta)
    graph = [aeo.article_ld(path, headline, desc, meta["published"], modified, image)]
    crumbs = visible_breadcrumb(html)
    if crumbs:
        from nt.pagekit import breadcrumb_ld
        graph.append(breadcrumb_ld(crumbs, path))
    faq = aeo.extract_faq(html)
    if faq:
        graph.append(aeo.faq_ld(faq, path))
    graph += [aeo.organization_ld()]
    body = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False, indent=2).replace("</", "<\\/")
    return ('<!-- BEGIN:NT-LD (generated by tools/apply-aeo.py) -->\n  <script type="application/ld+json">\n%s\n  </script>\n  <!-- END:NT-LD -->' % body)


def apply(html, path, meta):
    html = LD_RE.sub("", html)
    html = HD_RE.sub("", html)
    html = QA_RE.sub("", html)
    html = BY_RE.sub("", html)
    html = OF_RE.sub("", html)
    html = LK_RE.sub("", html)
    html = strip_old_ld(html)
    head = ld_block(html, path, meta)
    hb = head_block()
    html = html.replace("</head>", "  %s\n%s</head>" % (head, ("  %s\n" % hb) if hb else ""), 1)
    # byline right after the hero's meta strip
    by = aeo.byline(aeo.modified_for(path, meta), meta.get("lastVerified"), meta.get("published"))
    html, n = re.subn(r'(<div class="(?:page-meta|article-meta)">.*?</div>)', lambda m: m.group(1) + "\n    " + by, html, count=1, flags=re.S)
    if n != 1:
        raise SystemExit("ERROR: %s has no .page-meta strip for the byline" % path)
    if meta.get("quickAnswer"):
        qa = aeo.quick_answer(meta["quickAnswer"])
        html, n = re.subn(r'(<article class="article-body"[^>]*>)', lambda m: m.group(1) + "\n" + qa + "\n", html, count=1)
        if n != 1:
            raise SystemExit("ERROR: %s has no article body for the quick answer" % path)
    if meta.get("topic") in LINK_TOPICS:
        block = ('<!-- BEGIN:NT-LINKS -->\n<aside class="related-links" aria-label="Between Nashik and Trimbakeshwar"><h2 id="between-nashik-and-trimbakeshwar">Travelling between Nashik and Trimbakeshwar</h2>'
                 '<p>Both Kumbh Mela sites are on one route. See <a href="/blog/trimbakeshwar-to-nashik-distance-route/">Nashik to Trimbakeshwar distance, bus, jeep and cab</a>, '
                 '<a href="/transport/nashik-road-station-to-trimbakeshwar/">from Nashik Road railway station to Trimbakeshwar</a> and '
                 '<a href="/transport/trimbakeshwar-to-panchavati-ramkund/">between Trimbakeshwar and Ramkund</a>.</p></aside>\n<!-- END:NT-LINKS -->')
        if "<!-- BEGIN:NT-VERIFY" in html:
            html = html.replace("<!-- BEGIN:NT-VERIFY", block + "\n<!-- BEGIN:NT-VERIFY", 1)
        else:
            i = html.rindex("</article>")
            html = html[:i] + block + "\n" + html[i:]
    if meta.get("officialStatus"):
        o = meta["officialStatus"]
        box = ('<!-- BEGIN:NT-OFFICIAL -->\n<div class="official-box" role="note" data-official-status>\n  <p class="ob-title">Official status as of %s</p>\n  %s\n</div>\n<!-- END:NT-OFFICIAL -->'
               % (esc(fmt_date(o["asOf"])), o["html"]))
        html, n = re.subn(r"(<!-- END:NT-QA -->)", lambda m: m.group(1) + "\n" + box, html, count=1)
        if n != 1:
            raise SystemExit("ERROR: %s has officialStatus but no quick answer to follow" % path)
    return html


HEAD_ONLY = ["about/index.html", "contact/index.html", "404.html"]


def apply_head_only(html):
    """Hand-written pages that are not guides still get the optional Bing verification meta and
    cookieless analytics (env-driven), between the same NT-HEAD markers."""
    html = HD_RE.sub("", html)
    hb = head_block()
    return html.replace("</head>", ("  %s\n" % hb if hb else "") + "</head>", 1)


def main():
    check = "--check" in sys.argv
    pages = store.load("pages")["pages"]
    changed = 0
    for rel in HEAD_ONLY:
        full = os.path.join(ROOT, rel)
        if os.path.isfile(full):
            before = open(full, encoding="utf-8").read()
            after = apply_head_only(before)
            if after != before:
                changed += 1
                if not check:
                    with open(full, "w", encoding="utf-8") as fh:
                        fh.write(after)
    for path, meta in sorted(pages.items()):
        if meta.get("template") != "article" or meta.get("generated"):
            continue
        full = os.path.join(ROOT, path.strip("/"), "index.html")
        if not os.path.isfile(full):
            continue
        before = open(full, encoding="utf-8").read()
        after = apply(before, path, meta)
        if after != before:
            changed += 1
            if not check:
                with open(full, "w", encoding="utf-8") as fh:
                    fh.write(after)
    print("%s %d guide(s)" % ("would update" if check else "updated", changed))


if __name__ == "__main__":
    main()

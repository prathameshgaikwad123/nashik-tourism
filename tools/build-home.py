#!/usr/bin/env python3
"""
Generate the homepage (index.html): utility first, identity second.

    Header
    Search Nashik                 <- hero: the question, a search box, popular searches
    NASHIK — LIVE band            <- only during the live Kumbh phase (data-driven)
    Nashik Now                    <- weather, latest update, next event — each with a timestamp
    Kumbh 2027                    <- phase-aware: standard / live / reduced
    What are you looking for?     <- eight real questions, each showing how well we can answer it
    Latest updates
    Explore Nashik                <- preserved from the previous homepage
    Plan your trip                <- preserved
    Latest guides                 <- generated from posts.json, as before
    About / Trust                 <- preserved, plus the river story
    Footer

Nothing decorative sits above the answers: the hero is only as tall as its
content, and its photograph is applied by CSS at 720px+ so phones never download
it. Sections that survived from the previous homepage live in
tools/templates/home/ so their copy and markup are unchanged.
"""

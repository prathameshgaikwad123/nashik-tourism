def tpl(name):
    with open(os.path.join(TPL, name), encoding="utf-8") as fh:
        return fh.read()


def status_line(fid, facts, fallback):
    f = facts.get(fid)
    if not f:
        return fallback
    return {"verified": "Verified " + (render.fmt_date(f.get("verifiedAt"), short=True) if f.get("verifiedAt") else ""),
            "reported": "Reported, not yet confirmed",
            "not_verified": "Not yet verified",
            "disputed": "Sources differ"}[f["status"]]


def intent_tiles(facts):
    tiles = [
        ("Trimbakeshwar timings?", "Hours not yet confirmed. See what we know.", "/discover-nashik/trimbakeshwar/#quick-facts"),
        ("How do I reach Nashik?", "Air, train, bus and road, with official sources.", "/transport/"),
        ("When are the Kumbh dates?", status_line("kumbh.snan.1", facts, "Reported") + ".", "/kumbh-mela-2027/#dates"),
        ("Do I need a Kumbh pass?", "None announced that we can find. " + status_line("kumbh.pass.general", facts, "") + ".", "/kumbh-mela-2027/#passes"),
        ("Kumbh parking and roads?", "No official plan located yet.", "/kumbh-mela-2027/#parking-roads"),
        ("Where should I stay?", "Areas and options, and how to book.", "/blog/where-to-stay-nashik-kumbh-mela/"),
        ("Is it accessible?", "Access status of each place, honestly marked.", "/accessible-nashik/"),
        ("What&rsquo;s on?", "Events, each with its source.", "/events/"),
    ]
    return "".join('<li><a class="intent-tile" href="%s"><span class="it-q">%s</span><span class="it-a">%s</span></a></li>' % (h, q, a) for q, a, h in tiles)


def now_strip(built):
    updates = content.live_updates(limit=1)
    upcoming, _ = content.events()
    nxt = upcoming[0] if upcoming else None
    if updates:
        u = updates[0]
        upd = """<a class="now-card" href="/updates/#u-%s" style="text-decoration:none;">
        <p class="nc-label">Latest update</p><p class="nc-main">%s</p>
        <p class="nc-sub">%s</p><p class="nc-stamp">%s &middot; Source: %s &middot; Last checked %s</p></a>""" % (
            render.esc(u["id"]), render.esc(u["title"]), render.update_badge(render.effective_status(u)),
            "Published " + render.esc(render.fmt_date(u["publishedAt"], short=True)), render.esc(u["sourceName"]), render.esc(render.fmt_date(u["lastCheckedAt"], short=True)))
    else:
        upd = """<div class="now-card"><p class="nc-label">Latest update</p><p class="nc-main">No live updates</p>
        <p class="nc-sub">Nothing is published as live right now.</p><a class="nc-link" href="/updates/">Updates and archive</a></div>"""
    if nxt:
        ev = """<a class="now-card" href="/events/#e-%s" style="text-decoration:none;">
        <p class="nc-label">Next event</p><p class="nc-main">%s</p>
        <p class="nc-sub">%s &middot; %s</p><p class="nc-stamp">%s &middot; Last checked %s</p></a>""" % (
            render.esc(nxt["id"]), render.esc(nxt["title"]), render.esc(render.fmt_date(nxt["date"], weekday=True)), render.esc(nxt["location"]),
            "Verified" if nxt["verificationStatus"] == "verified" else "Reported, not yet confirmed",
            render.esc(render.fmt_date(nxt["lastCheckedAt"], short=True)) if nxt.get("lastCheckedAt") else "not recorded")
    else:
        ev = """<div class="now-card"><p class="nc-label">Next event</p><p class="nc-main">None listed</p>
        <p class="nc-sub">We list an event only with a named source.</p><a class="nc-link" href="/events/">Events</a></div>"""
    wx = """<div class="now-card"><p class="nc-label">Weather in Nashik</p>
        <div data-weather="compact" aria-live="polite"><p class="nc-sub">Loading the weather. Official forecasts: <a class="nc-link" href="https://mausam.imd.gov.in/" rel="noopener noreferrer">IMD</a>.</p></div></div>"""
    return """<section class="sec sec-alt" aria-labelledby="now-h"><div class="inner">
    <h2 class="sec-title" id="now-h">Nashik now</h2>
    <p class="sec-sub">What is happening, with the time each item was last checked.</p>
    <div class="now-grid">%s%s%s</div>
    <p class="link-row"><a class="btn btn-outline" href="/nashik-now/">Open Nashik Now</a></p>
  </div></section>""" % (wx, upd, ev)


def kumbh_block(prof, facts):
    def d(fid, label):
        f = facts[fid]
        return '<li><span class="kc-d">%s</span><span class="kc-l">%s &middot; %s</span></li>' % (
            render.esc(f["display"].replace("Monday ", "").replace("Tuesday ", "").replace("Saturday ", "").replace("Sunday ", "")),
            render.esc(label), render.esc(render.FACT_BADGES[f["status"]][1]))
    top = """<section class="sec" data-phase-id="preparation mela_open peak extended"%s aria-labelledby="k-h"><div class="inner">
    <div class="kumbh-card">
      <p class="kc-kicker">Simhastha Kumbh Mela 2026&ndash;28 &middot; %s</p>
      <h2 id="k-h">Kumbh Mela 2027</h2>
      <p>The Simhastha comes to Nashik and Trimbakeshwar. Dates and arrangements are still being confirmed, so each date here is marked with how sure we are.</p>
      <ul class="kc-dates">%s</ul>
      <p class="kc-caveat">Check with the official authority before travelling. <a class="lb-link" href="/kumbh-mela-2027/#dates">What is confirmed, and what is not</a></p>
      <div class="kc-actions">
        <a class="btn btn-primary" href="/kumbh-mela-2027/">Kumbh hub</a>
        <a class="btn btn-secondary" href="/kumbh-mela-2027/live-updates/">Live updates</a>
        <a class="btn btn-secondary" href="/kumbh-mela-2027/#passes">Passes: what is known</a>
      </div>
    </div></div></section>""" % ("" if prof["id"] in ("preparation", "mela_open", "peak", "extended") else " hidden",
                                  render.esc(prof["label"]),
                                  d("kumbh.mela.opening", "Mela opens") + d("kumbh.snan.1", "1st Amrit Snan") + d("kumbh.snan.2", "2nd Amrit Snan") + d("kumbh.snan.3.nashik", "3rd Amrit Snan (Nashik)"))
    reduced = """<section class="sec sec-stone" data-phase-id="post_kumbh evergreen"%s aria-labelledby="kr-h"><div class="inner">
    <h2 class="sec-title" id="kr-h">Kumbh Mela: guides and history</h2>
    <p class="sec-sub">The Simhastha is part of Nashik&rsquo;s story. Our Kumbh guides and the record of what was announced remain available.</p>
    <p class="link-row"><a class="btn btn-outline" href="/kumbh-mela-2027/">Kumbh hub</a><a class="btn btn-outline" href="/updates/archive/">Update archive</a></p>
  </div></section>""" % ("" if prof["id"] in ("post_kumbh", "evergreen") else " hidden")
    return top, reduced


def latest_updates_block():
    ups = content.live_updates(limit=3)
    lst = ('<div class="update-list">%s</div>' % "".join(render.update_card(u, tag="h3", compact=True) for u in ups)) if ups else \
        '<div class="empty-state"><h3>No live updates right now</h3><p>We publish an update only after an editor checks its source. See the <a href="/updates/archive/">archive</a> or <a href="/sources/">where to check for yourself</a>.</p></div>'
    return """<section class="sec" aria-labelledby="up-h"><div class="inner">
    <h2 class="sec-title" id="up-h">Latest updates</h2>
    <p class="sec-sub">Verified notices, each with its source and when it was last checked.</p>
    %s
    <p class="link-row"><a class="btn btn-outline" href="/updates/">All updates</a><a class="btn btn-outline" href="/updates/feed.xml">Feed</a></p>
  </div></section>""" % lst


def guides_cards():
    spec = importlib.util.spec_from_file_location("bhg", os.path.join(HERE, "build-home-guides.py"))
    bhg = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(bhg)
    posts = json.load(open(os.path.join(ROOT, "posts.json"), encoding="utf-8"))
    posts.sort(key=lambda p: p.get("date", ""), reverse=True)
    return "\n".join(bhg.build_card(p, featured=(i == 0)) for i, p in enumerate(posts[:3]))



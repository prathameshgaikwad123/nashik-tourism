#!/usr/bin/env python3
"""
Generate the crawler-facing files in the web root, from data, so they cannot drift
from the site:

  robots.txt          one policy: every search and AI-retrieval crawler explicitly allowed
  _redirects          every 301 (Cloudflare Pages / Netlify syntax), from data/redirects.json
                      plus automatic no-slash and .html -> clean-URL rules for every page
  llms.txt            what the site is, its editorial stance, and the key pages by group
  llms-full.txt       plain-text copy of the top pages (data/seo.json > llms.full)
  <indexnow-key>.txt  the IndexNow key file (the key is public by design)

Run last in build-all.py, after every page exists, because llms*.txt read the built HTML.

    python3 tools/build-seo-files.py
"""
import html as htmllib
import json
import os
import re
import sys
from html.parser import HTMLParser

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nt import store  # noqa: E402
from nt.paths import DATA, REPO, ROOT, SITE  # noqa: E402

# ── robots.txt ───────────────────────────────────────────────────────────────
# Every crawler that powers search or an answer engine. Listed explicitly so a
# platform's default (or a CDN's managed block) can never be read as the site's policy.
CRAWLERS = [
    ("Search engines", ["Googlebot", "Googlebot-Image", "Bingbot", "Applebot", "DuckDuckBot"]),
    ("AI retrieval / citation (these fetch a page to answer a user's question)",
     ["OAI-SearchBot", "ChatGPT-User", "PerplexityBot", "Perplexity-User", "Claude-SearchBot", "Claude-User"]),
    ("AI training / grounding",
     ["GPTBot", "ClaudeBot", "Google-Extended", "Applebot-Extended", "Amazonbot", "meta-externalagent", "CCBot", "Bytespider"]),
]
DISALLOW = [
    ("Private / utility paths", ["/login", "/admin", "/account", "/user", "/checkout", "/cart"]),
    ("Tracking and duplicate-URL parameters",
     ["/*?search=", "/*?sort=", "/*?order=", "/*?orderby=", "/*?page=", "/*?filter=", "/*?utm_"]),
]


def robots():
    rules = []
    for label, paths in DISALLOW:
        rules.append("# %s" % label)
        rules.extend("Disallow: %s" % p for p in paths)
    rules_txt = "\n".join(["Allow: /"] + rules)
    out = ["""# ==========================================================================
# nashiktourism.com robots.txt  (generated by tools/build-seo-files.py - edit there)
#
# !! The Cloudflare "Managed robots.txt" / "Block AI bots" feature MUST stay OFF
# !! (Cloudflare dashboard > Security > Bots, and Caching > Configuration).
# !! When it is on, Cloudflare prepends its own block that Disallows GPTBot,
# !! ClaudeBot, Google-Extended, CCBot, Applebot-Extended, Amazonbot and
# !! meta-externalagent, which contradicts this file and keeps the site out of
# !! AI answers. This file is the only policy.
#
# Policy: open to search engines and AI crawlers. Block only utility paths and
# tracking parameters.
#
# /search/ is deliberately crawlable but carries <meta name="robots" content="noindex">,
# so crawlers can read the noindex and drop it. Do not Disallow it: a disallowed URL
# can still be indexed from links without a noindex ever being seen.
#
# Note on groups: a crawler obeys only the single most specific group that matches it.
# Every crawler is therefore listed in ONE group sharing the same rules, so the
# Disallow lines below apply to all of them (a bare "User-agent: X / Allow: /" group
# would silently ignore them).
# =========================================================================="""]
    for label, agents in CRAWLERS:
        out.append("\n# ---------- %s ----------" % label)
        out.extend("User-agent: %s" % a for a in agents)
    out.append("\n# ---------- Everyone else ----------")
    out.append("User-agent: *")
    out.append("\n" + rules_txt)
    out.append("\n# ---------- Sitemap ----------")
    out.append("Sitemap: %s/sitemap.xml" % SITE)
    return "\n".join(out) + "\n"


# ── Page inventory ───────────────────────────────────────────────────────────
def page_url(full):
    rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
    if rel == "index.html":
        return "/"
    return "/" + rel[:-len("index.html")] if rel.endswith("/index.html") else "/" + rel


def all_pages():
    out = {}
    for dp, _d, files in os.walk(ROOT):
        if "index.html" in files:
            full = os.path.join(dp, "index.html")
            out[page_url(full)] = full
    return out


# ── _redirects ───────────────────────────────────────────────────────────────
def load_redirects():
    return json.load(open(os.path.join(DATA, "redirects.json"), encoding="utf-8"))["redirects"]


def redirects_file(pages):
    explicit = load_redirects()
    sources = {r["from"] for r in explicit}
    lines = ["""# Generated by tools/build-seo-files.py from data/redirects.json - do not edit here.
# Cloudflare Pages and Netlify both read this file from the web root. All rules are 301.
#
# www -> apex is a HOST rule, which a static _redirects file cannot express. Create it in
# Cloudflare (Rules > Redirect Rules): when Hostname equals www.nashiktourism.com,
# redirect (dynamic) to concat("https://nashiktourism.com", http.request.uri.path) with
# status 301 and "preserve query string" on. Canonical tags already name the apex.
"""]
    lines.append("# --- retired / mistyped URLs ---")
    for r in explicit:
        lines.append("%s %s 301" % (r["from"], r["to"]))
    lines.append("\n# --- no trailing slash -> slash (every real page) ---")
    for url in sorted(pages):
        if url != "/" and url.endswith("/") and url[:-1] not in sources:
            lines.append("%s %s 301" % (url[:-1], url))
    lines.append("\n# --- .html -> clean URL (every real page) ---")
    for url in sorted(pages):
        if url == "/":
            continue   # /index.html -> / is handled by the host itself
        if url[:-1] + ".html" not in sources:
            lines.append("%s.html %s 301" % (url[:-1], url))
    return "\n".join(lines) + "\n"


# ── llms.txt ─────────────────────────────────────────────────────────────────
class Extract(HTMLParser):
    """Title, meta description and the readable text of <main>."""
    SKIP = {"script", "style", "nav", "header", "footer", "form", "dialog", "svg", "button", "noscript"}
    BLOCK = {"p", "li", "h1", "h2", "h3", "h4", "tr", "div", "section", "article", "aside", "dt", "dd", "table", "ul", "ol", "blockquote"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.title, self.desc, self.text = "", "", []
        self._in_title = False
        self._in_main = False
        self._skip = 0
        self._skip_cls = []
        self._tags = []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "title":
            self._in_title = True
        elif tag == "meta" and a.get("name") == "description":
            self.desc = a.get("content", "")
        elif tag == "main":
            self._in_main = True
        if not self._in_main:
            return
        cls = a.get("class") or ""
        hidden = "sr-only" in cls and tag != "h2"
        if tag in self.SKIP or hidden or "read-progress" in cls or "toc-card" in cls or "signup" in cls or "breadcrumb" in cls:
            self._skip += 1
            self._tags.append(tag)
        elif self._skip:
            self._tags.append(tag) if tag == self._tags[-1] else None
        if tag == "br":
            self.text.append(" ")
        if tag in ("h1", "h2", "h3"):
            self.text.append("\n\n" + "#" * int(tag[1]) + " ")
        elif tag == "li":
            self.text.append("\n- ")
        elif tag in ("td", "th"):
            self.text.append(" | ")
        elif tag in self.BLOCK:
            self.text.append("\n")

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False
        elif tag == "main":
            self._in_main = False
        if self._skip and self._tags and self._tags[-1] == tag:
            self._tags.pop()
            self._skip -= 1
        if self._in_main and tag in self.BLOCK and not self._skip:
            self.text.append("\n")

    def handle_data(self, data):
        if self._in_title:
            self.title += data
        elif self._in_main and not self._skip:
            self.text.append(data)


def read_page(full):
    p = Extract()
    p.feed(open(full, encoding="utf-8").read())
    text = "".join(p.text)
    text = re.sub(r"[ \t\r\f\v]+", " ", text)
    text = re.sub(r" ?\n ?", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    title = re.sub(r"\s*[|–-]\s*NashikTourism\.com\s*$", "", htmllib.unescape(p.title)).strip()
    return title, htmllib.unescape(p.desc).strip(), text


def one_line(desc, limit=200):
    desc = re.sub(r"\s+", " ", desc)
    if len(desc) <= limit:
        return desc
    cut = desc[:limit].rsplit(" ", 1)[0]
    return cut.rstrip(" ,;:-") + "…"


def llms(pages, cfg):
    out = ["# NashikTourism.com", "", "> " + cfg["tagline"], "", cfg["stance"], "",
           "Language: English (with short Hindi and Marathi answers on the distance guide). "
           "Region: Nashik district, Maharashtra, India. Pages show a \"Last updated\" and \"Last verified\" date.",
           "", "Full text of the main pages: %s/llms-full.txt" % SITE, ""]
    missing = []
    for sec in cfg["sections"]:
        out.append("## " + sec["title"])
        out.append("")
        for path in sec["pages"]:
            if path not in pages:
                missing.append(path)
                continue
            title, desc, _ = read_page(pages[path])
            out.append("- [%s](%s%s): %s" % (title, SITE, path, one_line(desc)))
        out.append("")
    return "\n".join(out).rstrip() + "\n", missing


def llms_full(pages, cfg):
    out = ["# NashikTourism.com - full text of key pages", "",
           "> " + cfg["tagline"], "", cfg["stance"], "",
           "Each page below is reproduced as plain text. The live page is the source of truth; "
           "check its \"Last updated\" and \"Last verified\" dates and its per-claim status labels.", ""]
    for path in cfg["full"]:
        if path not in pages:
            continue
        title, desc, text = read_page(pages[path])
        out += ["", "-" * 72, "", "# %s" % title, "URL: %s%s" % (SITE, path), "", text, ""]
    return "\n".join(out).rstrip() + "\n"


def write(name, content):
    with open(os.path.join(ROOT, name), "w", encoding="utf-8") as fh:
        fh.write(content)


def main():
    seo = json.load(open(os.path.join(DATA, "seo.json"), encoding="utf-8"))
    pages = all_pages()
    write("robots.txt", robots())
    write("_redirects", redirects_file(pages))
    body, missing = llms(pages, seo["llms"])
    write("llms.txt", body)
    write("llms-full.txt", llms_full(pages, seo["llms"]))
    key = open(os.path.join(REPO, seo["indexnow"]["keyFile"]), encoding="utf-8").read().strip()
    write(key + ".txt", key + "\n")
    print("robots.txt, _redirects (%d explicit), llms.txt (%d chars), llms-full.txt, IndexNow key file written"
          % (len(load_redirects()), len(body)))
    for m in missing:
        print("  note: llms.txt section lists %s, which does not exist (yet)" % m)


if __name__ == "__main__":
    main()
